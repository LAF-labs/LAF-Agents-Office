#!/usr/bin/env node

const fs = require("node:fs");
const path = require("node:path");
const { spawnSync } = require("node:child_process");

const root = path.resolve(__dirname, "..");
const manifestPath = "shared/generated-artifacts.json";

function fail(message) {
  console.error(`startup-office generated artifacts check failed: ${message}`);
  process.exit(1);
}

function read(relativePath) {
  return fs.readFileSync(path.join(root, relativePath), "utf8");
}

function run(command, args) {
  const result = spawnSync(command, args, {
    cwd: root,
    encoding: "utf8",
    maxBuffer: 1024 * 1024,
  });
  if (result.status !== 0) {
    fail(`${command} ${args.join(" ")} failed: ${(result.stderr || result.stdout).trim()}`);
  }
  return result.stdout;
}

function assertContains(relativePath, snippets, label) {
  const body = read(relativePath);
  for (const snippet of snippets) {
    if (!body.includes(snippet)) fail(`${label} is missing ${snippet} in ${relativePath}`);
  }
}

const pkg = JSON.parse(read("package.json"));
if (
  pkg.scripts?.["startup-office:generated-artifacts"] !==
  "node scripts/check-startup-office-generated-artifacts.cjs"
) {
  fail("package.json must expose startup-office:generated-artifacts");
}

const manifest = JSON.parse(read(manifestPath));
if (manifest.version !== "generated-artifacts.v1") {
  fail(`unexpected generated artifact manifest version ${manifest.version || "<missing>"}`);
}
if (!Array.isArray(manifest.artifacts) || manifest.artifacts.length === 0) {
  fail("generated artifact manifest must list at least one artifact");
}

const artifactPaths = new Set();
for (const artifact of manifest.artifacts) {
  for (const field of ["path", "source", "command", "checker"]) {
    if (!artifact[field]) fail(`generated artifact entry is missing ${field}`);
  }
  if (artifactPaths.has(artifact.path)) fail(`duplicate generated artifact ${artifact.path}`);
  artifactPaths.add(artifact.path);
  if (!fs.existsSync(path.join(root, artifact.path))) fail(`missing generated artifact ${artifact.path}`);
  if (!fs.existsSync(path.join(root, artifact.source))) fail(`missing generated source ${artifact.source}`);
  if (!fs.existsSync(path.join(root, artifact.checker))) fail(`missing generated checker ${artifact.checker}`);
}

const trackedFiles = run("git", ["ls-files"]).trim().split(/\r?\n/).filter(Boolean);
const trackedGeneratedFiles = trackedFiles.filter((relativePath) => {
  if (relativePath.includes(".generated.")) return true;
  const body = read(relativePath).slice(0, 160);
  return body.startsWith("// Generated ") || body.startsWith("// Code generated ");
});
for (const relativePath of trackedGeneratedFiles) {
  if (!artifactPaths.has(relativePath)) fail(`${relativePath} is generated but missing from ${manifestPath}`);
}

assertContains(
  "web/src/api/workspacePermissions.ts",
  ["// Generated from shared/workspace-permissions.json by scripts/check-workspace-permission-catalog.cjs."],
  "workspace permission generated artifact",
);
assertContains(
  "web/src/lib/avatarSprites.generated.ts",
  ["// Code generated by scripts/generate-avatar-sprites.mjs. DO NOT EDIT."],
  "avatar sprite generated artifact",
);

run("node", ["scripts/check-workspace-permission-catalog.cjs"]);
const avatarPath = "web/src/lib/avatarSprites.generated.ts";
const avatarBefore = read(avatarPath);
run("node", ["scripts/generate-avatar-sprites.mjs"]);
const avatarAfter = read(avatarPath);
if (avatarAfter !== avatarBefore) {
  fs.writeFileSync(path.join(root, avatarPath), avatarBefore);
  fail(`${avatarPath} is out of sync with assets/avatar-system/base-sprites.json`);
}

assertContains(
  "scripts/startup-office-beta-release-gate.cjs",
  ['"startup-office:generated-artifacts"'],
  "beta release gate",
);
assertContains(
  "docs/specs/SILICON-VALLEY-PRODUCTION-AUDIT.md",
  ["startup-office:generated-artifacts", "Generated artifacts now have a tracked manifest"],
  "production audit generated artifact evidence",
);

console.log(`startup-office generated artifacts check passed: ${artifactPaths.size} artifacts`);
